function resolveGalleryImage($filename) {
    if (str_starts_with($filename, 'http')) return $filename;
    $clean = ltrim($filename, '/');
    if (file_exists(__DIR__ . '/' . $clean)) return $clean;
    if (file_exists(__DIR__ . '/img/' . $clean)) return 'img/' . $clean;
    
    $prefix = explode('....', $clean)[0];
    $prefix = explode('..', $prefix)[0];
    $files = glob(__DIR__ . '/img/' . $prefix . '*');
    if (!empty($files)) {
        return 'img/' . basename($files[0]);
    }
    return 'img/' . $clean;
}
